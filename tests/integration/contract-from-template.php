<?php
require __DIR__ . '/guard.php';
use App\Guesstimate\Auth\AccessDenied;
use App\Guesstimate\Contracts\{Contract, ContractEvent, ContractHtml, ContractService, ContractTemplate, ContractTemplateService, ContractVersion, DraftConflict, TemplateDocument, TemplateForm};
use App\Guesstimate\Offers\Offer;
use Illuminate\Support\Facades\DB;
$pass = 0; $fail = 0;
$ok = function (string $n, $c) use (&$pass, &$fail) { $c ? $pass++ : $fail++; echo($c ? '  ok  ' : ' FAIL '), $n, "\n"; };
$throws = function (callable $f, string $class = Throwable::class) { try { $f(); return false; } catch (Throwable $e) { return $e instanceof $class; } };
wp_set_current_user(1);
$s = app(ContractTemplateService::class); $c = app(ContractService::class);
$sum = fn () => DB::table('gst_publications')->orderBy('id')->pluck('snapshot', 'id')->map(fn ($x) => md5($x))->all();
$before = $sum();
$form = TemplateForm::document(['header' => '<p>Firma <span data-var="client.company_name">Nazwa firmy</span></p>', 'body' => '<h1>Umowa</h1><p class="ct-par">Przedmiot</p><p>Tekst C:\\plik „cudzysłów” 😀</p><table><tbody><tr><td>a</td></tr></tbody></table><hr class="ct-break"><p>Dalej</p>', 'footer' => '<p>Strona <span data-var="page.number">n</span></p>']);
$t = $s->create('Integracja', $form['body']);
$v = $t->fresh()->currentVersion;
$ok('treść zapisana co do bajtu', $v->body === $form['body']);
$ok('ponowne czyszczenie nie zmienia bajtów', TemplateForm::document(TemplateDocument::parse($form['body']))['body'] === $form['body']);
$hash = hash('sha256', $v->body);
$ok('zły skrót blokuje zapis', $throws(fn () => $s->saveDraft($t->fresh(), 'x', str_repeat('0', 64)), DraftConflict::class));
$ok('zły skrót blokuje zatwierdzenie', $throws(fn () => $s->approve($t->fresh(), str_repeat('0', 64)), DraftConflict::class));
$ok('po odrzuceniach treść nietknięta', $t->fresh()->currentVersion->body === $form['body']);
$a = $s->approve($t->fresh(), $hash);
$ok('zatwierdzona ze skrótem', $a->isApproved() && $a->content_hash === hash('sha256', $form['body']) && $a->fresh()->isIntact());
$offer = Offer::whereNotNull('client_id')->whereNotNull('current_version_id')->orderByDesc('id')->get()->first(fn ($o) => $o->currentVersion?->result);
$contract = $c->create($offer, $a, 'Umowa z edytora');
$cv = $contract->fresh()->currentVersion;
$ok('umowa = szablon co do bajtu, z nagłówkiem i stopką', $cv->body === $form['body']);
$parts = TemplateDocument::parse($cv->body);
$ok('sekcje czytelne z umowy', str_contains($parts['header'], 'client.company_name') && str_contains($parts['footer'], 'page.number') && str_contains($parts['body'], 'C:\\plik'));
$ok('umowa zatwierdzalna, skrót obejmuje nagłówek', ($x = $c->approve($contract->fresh())) && $x->fresh()->isIntact());
DB::table('gst_contract_versions')->where('id', $cv->id)->update(['body' => str_replace('Firma', 'Inna', $cv->body)]);
$ok('zmiana samego nagłówka wykryta skrótem', ! ContractVersion::find($cv->id)->isIntact());
DB::table('gst_contract_versions')->where('id', $cv->id)->update(['body' => $form['body']]);
$blank = $s->create('Pusty z nagłówkiem', TemplateDocument::compose('<p>nagłówek</p>', '<p><br></p>', ''));
$ok('sam nagłówek to nie treść', $throws(fn () => $s->approve($blank->fresh()), InvalidArgumentException::class));
$imp = $s->import('Imp', TemplateDocument::compose('', '<p>x</p>', ''), ['ostrzeżenie'], str_repeat('a', 64));
$ok('import wymaga potwierdzenia', $throws(fn () => $s->approve($imp->fresh()), InvalidArgumentException::class));
$dup = $s->duplicate($imp->fresh()->currentVersion, 'Kopia importu');
$ok('kopia nie omija potwierdzenia', $throws(fn () => $s->approve($dup->fresh()), InvalidArgumentException::class));
$ok('z potwierdzeniem przechodzi', $s->approve($dup->fresh(), null, true)->isApproved());
$ok('dziennik importu bez treści', ! str_contains((string) DB::table('gst_contract_events')->where('template_id', $imp->id)->value('payload'), '<p>x</p>'));
$s->archive($imp->fresh());
$ok('archiwum blokuje zapis', $throws(fn () => $s->saveDraft($imp->fresh(), 'y'), InvalidArgumentException::class));
$ok('archiwum blokuje zatwierdzenie', $throws(fn () => $s->approve($imp->fresh(), null, true), InvalidArgumentException::class));
$s->rename($t->fresh(), 'Nowa nazwa', 'opis');
$ok('zmiana nazwy po zatwierdzeniu, bez zmiany treści', $t->fresh()->name === 'Nowa nazwa' && $t->fresh()->currentVersion->isIntact());
$ok('zmiana nazwy w dzienniku', ContractEvent::where('template_id', $t->id)->where('type', 'template_renamed')->exists());
$s->rename($t->fresh(), 'Nowa nazwa', 'opis');
$ok('bez zmian bez wpisu', ContractEvent::where('template_id', $t->id)->where('type', 'template_renamed')->count() === 1);
$emp = get_user_by('login', 't8emp')->ID; wp_set_current_user($emp);
foreach (['duplicate' => fn () => $s->duplicate($a, 'x'), 'import' => fn () => $s->import('x', 'y', [], 'z'), 'rename' => fn () => $s->rename($t->fresh(), 'x', null), 'archive' => fn () => $s->archive($t->fresh())] as $name => $f) {
	$ok("pracownik: $name odrzucone", $throws($f, AccessDenied::class));
}
$ok('publikacje bez zmian', $sum() === $before);
echo "WYNIK: $pass ok, $fail błędów\n";
