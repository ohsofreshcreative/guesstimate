<?php
require __DIR__ . '/guard.php';
use App\Guesstimate\Auth\AccessDenied;
use App\Guesstimate\Clients\Client;
use App\Guesstimate\Contracts\{Contract, ContractEvent, ContractService, ContractSnapshot, ContractTemplateService, ContractValues, ContractVersion, DraftConflict, TemplateDocument, TemplateVariables};
use App\Guesstimate\Offers\Offer;
use App\Guesstimate\Settings\SettingsRepository;
use Illuminate\Support\Facades\DB;
$pass = 0; $fail = 0;
$ok = function (string $n, $c) use (&$pass, &$fail) { $c ? $pass++ : $fail++; echo($c ? '  ok  ' : ' FAIL '), $n, "\n"; };
$throws = function (callable $f, string $class = Throwable::class) { try { $f(); return false; } catch (Throwable $e) { return $e instanceof $class; } };
wp_set_current_user(1);
$sum = fn () => [DB::table('gst_publications')->orderBy('id')->pluck('snapshot', 'id')->map(fn ($x) => md5($x))->all(), DB::table('gst_offer_versions')->orderBy('id')->get(['id', 'low_min', 'mid_min', 'high_max', 'result'])->map(fn ($x) => md5(json_encode($x)))->all()];
$before = $sum();
$tok = fn ($k) => sprintf('<span class="ct-var" data-var="%s" contenteditable="false">%s</span>', $k, TemplateVariables::all()[$k]);
$s = app(ContractTemplateService::class); $c = app(ContractService::class);
$bodyT = TemplateDocument::compose('<p>' . $tok('contractor.company_name') . '</p>', '<p>A ' . $tok('client.company_name') . ' ' . $tok('offer.number') . ' ' . $tok('offer.variant') . ' ' . $tok('offer.amount_variant') . ' ' . $tok('offer.amount_range') . ' ' . $tok('offer.pages') . ' ' . $tok('offer.date') . ' ' . $tok('terms.place') . '</p>', '');
$t = $s->create('T9', $bodyT); $a = $s->approve($t->fresh());
$offer = Offer::whereNotNull('client_id')->whereNotNull('current_version_id')->orderByDesc('id')->get()->first(fn ($o) => $o->currentVersion?->result && $o->currentVersion->isBudget());
$cv = $offer->currentVersion;
app(SettingsRepository::class)->set('contractor', ['company_name' => 'W1', 'address' => '', 'nip' => '', 'representative' => '']);
$contract = $c->create($offer, $a, 'K', ['terms.place' => '5 zł', 'offer.number' => 'X']);
$v = $contract->fresh()->currentVersion; $d = $v->data_snapshot;
$ok('schema 2', $d['schema'] === 3);
$ok('treść = szablon co do bajtu po generowaniu', $v->body === $bodyT);
$ok('wartości w snapshocie', $d['values'] === ['terms.place' => '5 zł', 'offer.number' => 'X']);
$ok('dane źródłowe obok wartości ręcznych', $d['offer']['number'] === $offer->number && ContractValues::automatic($d)['offer.number'] === $offer->number);
$sel = $cv->selected_variant;
$ok('kwoty wariantu z kolumn wersji', $d['pricing']['amounts']['variant'] === ['min' => $cv->{$sel . '_min'}, 'max' => $cv->{$sel . '_max'}]);
$ok('widełki min Low – max High', $d['pricing']['amounts']['range'] === ['min' => $cv->low_min, 'max' => $cv->high_max]);
$ok('mapa i wariant w snapshocie', is_array($d['offer']['pages']) && is_string($d['offer']['variant']));
$ok('kwota umowy nie pochodzi z oferty', ContractValues::resolved($d)['contract.amount'] === null);
$r = ContractValues::render($v->body, $d); $ok('brak surowych tokenów i pustych', ! preg_match('/data-var|undefined|\bnull\b|\[brak/', $r));
$hash = $v->snapshotHash();
$client = Client::find($offer->client_id); $old = $client->company_name;
$client->update(['company_name' => 'Nowa firma']);
app(SettingsRepository::class)->set('contractor', ['company_name' => 'W2', 'address' => '', 'nip' => '', 'representative' => '']);
$v2 = ContractVersion::find($v->id);
$ok('snapshot niezależny od zmian', ContractValues::resolved($v2->data_snapshot)['client.company_name'] === $old && ContractValues::resolved($v2->data_snapshot)['contractor.company_name'] === 'W1');
$diff = ContractValues::diff($v2->body, $v2->data_snapshot, ContractSnapshot::of($offer->fresh(), $offer->fresh()->currentVersion));
$ok('różnice tylko źródła', collect($diff)->pluck('key')->sort()->values()->all() === ['client.company_name', 'contractor.company_name']);
$ok('zły skrót blokuje odświeżenie', $throws(fn () => $c->refresh($contract->fresh(), str_repeat('0', 64)), DraftConflict::class));
$ok('zły skrót blokuje zapis wartości', $throws(fn () => $c->saveValues($contract->fresh(), ['terms.place' => 'x'], str_repeat('0', 64)), DraftConflict::class));
$bodyBefore = $v2->body;
$c->refresh($contract->fresh(), $v2->snapshotHash()); $v3 = ContractVersion::find($v->id);
$ok('odświeżenie bierze nowe dane', ContractValues::resolved($v3->data_snapshot)['client.company_name'] === 'Nowa firma');
$ok('odświeżenie zachowuje ręczne', $v3->data_snapshot['values'] === ['terms.place' => '5 zł', 'offer.number' => 'X']);
$ok('odświeżenie nie dotyka treści', $v3->body === $bodyBefore);
$ok('dziennik odświeżenia', ContractEvent::where('contract_id', $contract->id)->where('type', 'data_refreshed')->exists());
$c->saveValues($contract->fresh(), ['offer.number' => '', 'client.phone' => 'pominięte'], $v3->snapshotHash()); $v4 = ContractVersion::find($v->id);
$ok('dziennik wartości bez treści', ! str_contains(json_encode(ContractEvent::where('contract_id', $contract->id)->where('type', 'values_saved')->value('payload')), 'pominięte'));
$c->saveValues($contract->fresh(), ['terms.place' => ''], $v4->snapshotHash());
$ok('brak pola blokuje zatwierdzenie', $throws(fn () => $c->approve($contract->fresh()), InvalidArgumentException::class));
$c->saveValues($contract->fresh(), ['terms.place' => '7 zł'], ContractVersion::find($v->id)->snapshotHash());
$ap = $c->approve($contract->fresh());
$ok('zatwierdzona, skrót obejmuje wartości', $ap->isApproved() && $ap->fresh()->isIntact());
$ok('zatwierdzonej nie można edytować', $throws(fn () => $c->saveValues($contract->fresh(), ['terms.place' => '9 zł'], $ap->fresh()->snapshotHash()), InvalidArgumentException::class));
$ok('zatwierdzonej nie można odświeżyć', $throws(fn () => $c->refresh($contract->fresh(), $ap->fresh()->snapshotHash()), InvalidArgumentException::class));
$rawA = ContractVersion::find($ap->id)->getAttributes()['data_snapshot'];
$client->update(['company_name' => 'Trzecia']);
$n = $c->newVersion($contract->fresh());
$ok('nowa wersja przenosi ręczne', $n->data_snapshot['values']['terms.place'] === '7 zł');
$ok('nowa wersja z aktualnych danych', ContractValues::resolved($n->data_snapshot)['client.company_name'] === 'Trzecia');
$ok('zatwierdzona v1 bez zmian', ContractVersion::find($ap->id)->getAttributes()['data_snapshot'] === $rawA && ContractVersion::find($ap->id)->isIntact());
DB::table('gst_contract_versions')->where('id', $ap->id)->update(['data_snapshot' => str_replace('7 z', '9 z', $rawA)]);
$ok('podmiana wartości w bazie wykryta skrótem', ! ContractVersion::find($ap->id)->isIntact());
$ok('podmiana faktycznie zaszła', ContractVersion::find($ap->id)->getAttributes()['data_snapshot'] !== $rawA);
DB::table('gst_contract_versions')->where('id', $ap->id)->update(['data_snapshot' => $rawA]);
$k2 = $c->create($offer->fresh(), $a, 'K2');
$ok('zbyt długa wartość odrzucona', $throws(fn () => $c->saveValues($k2->fresh(), ['terms.place' => str_repeat('a', 2001)], $k2->fresh()->currentVersion->snapshotHash()), InvalidArgumentException::class));
$emp = get_user_by('login', 't8emp')->ID; wp_set_current_user($emp);
$h = $k2->fresh()->currentVersion->snapshotHash();
$ok('pracownik: wartości odrzucone', $throws(fn () => $c->saveValues($k2->fresh(), [], $h), AccessDenied::class));
$ok('pracownik: odświeżenie odrzucone', $throws(fn () => $c->refresh($k2->fresh(), $h), AccessDenied::class));
wp_set_current_user(1);
$client->update(['company_name' => $old]);
$ok('kwoty i publikacje bez zmian', $sum() === $before);
echo "WYNIK: $pass ok, $fail błędów\n";
